#!/usr/bin/env python3
"""
Test Runner for 2 Blind Mice Game
Run this script to execute all tests and generate a comprehensive report.
"""

import sys
import os
import subprocess
import time
from datetime import datetime

def run_test_suite():
    """Run the complete test suite and generate report"""
    
    print("=" * 60)
    print("2 BLIND MICE - GAME TESTING SUITE")
    print("=" * 60)
    print(f"Test Run Started: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
    print()
    
    # Check if test_game.py exists
    if not os.path.exists("test_game.py"):
        print("❌ ERROR: test_game.py not found!")
        print("Please ensure the test file is in the current directory.")
        return False
    
    try:
        # Run the test suite
        print("🔍 Running test suite...")
        start_time = time.time()
        
        result = subprocess.run([
            sys.executable, "test_game.py"
        ], capture_output=True, text=True, timeout=300)  # 5 minute timeout
        
        end_time = time.time()
        execution_time = end_time - start_time
        
        print("✅ Test execution completed!")
        print(f"⏱️  Execution time: {execution_time:.2f} seconds")
        print()
        
        # Display test results
        print("📊 TEST RESULTS:")
        print("-" * 40)
        
        if result.returncode == 0:
            print("✅ All tests passed!")
            print("🎉 Game is ready for deployment!")
        else:
            print("❌ Some tests failed!")
            print("🔧 Please review the test output below:")
        
        print()
        print("📋 DETAILED OUTPUT:")
        print("-" * 40)
        print(result.stdout)
        
        if result.stderr:
            print("⚠️  ERRORS/WARNINGS:")
            print("-" * 40)
            print(result.stderr)
        
        # Generate summary report
        generate_summary_report(result.returncode == 0, execution_time)
        
        return result.returncode == 0
        
    except subprocess.TimeoutExpired:
        print("❌ ERROR: Test execution timed out!")
        print("Tests took longer than 5 minutes to complete.")
        return False
    except Exception as e:
        print(f"❌ ERROR: Failed to run tests: {e}")
        return False

